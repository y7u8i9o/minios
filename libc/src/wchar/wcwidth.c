int wcwidth(wchar_t wc)
{
    unsigned c = (unsigned)wc;
    if (!c) return 0;
    if (c < 32 || (c >= 0x7f && c < 0xa0) || c > 0x10ffff ||
        (c >= 0xd800 && c <= 0xdfff)) return -1;
    size_t lo = 0, hi = sizeof zero / sizeof *zero;
    while (lo < hi) {
        size_t mid = lo + (hi - lo) / 2;
        if (c < zero[mid].first) hi = mid;
        else if (c > zero[mid].last) lo = mid + 1;
        else return 0;
    }
    return 1 + (c >= 0x1100 && (c <= 0x115f || c == 0x2329 || c == 0x232a ||
        (c >= 0x2e80 && c <= 0xa4cf && c != 0x303f) ||
        (c >= 0xac00 && c <= 0xd7a3) || (c >= 0xf900 && c <= 0xfaff) ||
        (c >= 0xfe10 && c <= 0xfe19) || (c >= 0xfe30 && c <= 0xfe6f) ||
        (c >= 0xff00 && c <= 0xff60) || (c >= 0xffe0 && c <= 0xffe6) ||
        (c >= 0x1f300 && c <= 0x1faff) || (c >= 0x20000 && c <= 0x3fffd)));
}

int wcswidth(const wchar_t *s, size_t n)
{
    int total = 0;
    while (n-- && *s) {
        int w = wcwidth(*s++);
        if (w < 0 || total > 2147483647 - w) return -1;
        total += w;
    }
    return total;
}
